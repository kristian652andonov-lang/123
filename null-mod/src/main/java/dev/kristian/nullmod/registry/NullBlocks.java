package dev.kristian.nullmod.registry;

import dev.kristian.nullmod.NullMod;
import java.util.List;
import java.util.function.ToIntFunction;
import net.minecraft.core.BlockPos;
import net.minecraft.world.entity.EntityType;
import net.minecraft.world.level.BlockGetter;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.CarpetBlock;
import net.minecraft.world.level.block.RotatedPillarBlock;
import net.minecraft.world.level.block.SoundType;
import net.minecraft.world.level.block.TransparentBlock;
import net.minecraft.world.level.block.state.BlockBehaviour;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.material.MapColor;
import net.minecraft.world.level.material.PushReaction;
import net.neoforged.neoforge.registries.DeferredBlock;
import net.neoforged.neoforge.registries.DeferredRegister;

/**
 * NULL's blocks. None of them have items: they only ever appear because the world is
 * corrupting, or inside the NULL dimension. Textures and models are generated by
 * tools/generate_assets.py.
 */
public final class NullBlocks {
    public static final DeferredRegister.Blocks BLOCKS = DeferredRegister.createBlocks(NullMod.MODID);

    // ---- Corruption (Stages 1-3) -------------------------------------------------------
    /** Completely black: no detail at all. */
    public static final DeferredBlock<Block> BLACK_BLOCK = BLOCKS.registerSimpleBlock("black_block", corrupted(MapColor.COLOR_BLACK));
    /** The magenta and black missing-texture checkerboard. */
    public static final DeferredBlock<Block> MISSING_BLOCK = BLOCKS.registerSimpleBlock("missing_block", corrupted(MapColor.COLOR_MAGENTA));
    public static final DeferredBlock<Block> ERROR_BLOCK = BLOCKS.registerSimpleBlock("error_block", corrupted(MapColor.COLOR_PURPLE));
    public static final DeferredBlock<Block> ERROR_STRIPES = BLOCKS.registerSimpleBlock("error_stripes", corrupted(MapColor.COLOR_PURPLE));
    public static final DeferredBlock<Block> ERROR_NOISE = BLOCKS.registerSimpleBlock("error_noise", corrupted(MapColor.COLOR_GRAY));
    public static final DeferredBlock<Block> ERROR_SHIFT = BLOCKS.registerSimpleBlock("error_shift", corrupted(MapColor.COLOR_MAGENTA));
    /** Animated television static. */
    public static final DeferredBlock<Block> STATIC_BLOCK = BLOCKS.registerSimpleBlock("static_block",
            corrupted(MapColor.COLOR_LIGHT_GRAY).lightLevel(state -> 3));
    public static final DeferredBlock<Block> CORRUPTED_GRASS_BLOCK = BLOCKS.registerSimpleBlock("corrupted_grass_block",
            corrupted(MapColor.GRASS).strength(0.6F));
    public static final DeferredBlock<Block> CORRUPTED_DIRT = BLOCKS.registerSimpleBlock("corrupted_dirt",
            corrupted(MapColor.DIRT).strength(0.5F));
    public static final DeferredBlock<Block> CORRUPTED_STONE = BLOCKS.registerSimpleBlock("corrupted_stone",
            corrupted(MapColor.STONE).strength(1.5F, 6.0F));
    public static final DeferredBlock<Block> CORRUPTED_SAND = BLOCKS.registerSimpleBlock("corrupted_sand",
            corrupted(MapColor.SAND).strength(0.5F));
    public static final DeferredBlock<RotatedPillarBlock> CORRUPTED_LOG = BLOCKS.registerBlock("corrupted_log",
            RotatedPillarBlock::new, corrupted(MapColor.WOOD).strength(2.0F));
    public static final DeferredBlock<Block> CORRUPTED_LEAVES = BLOCKS.registerSimpleBlock("corrupted_leaves",
            corrupted(MapColor.PLANT).strength(0.2F).noOcclusion().isSuffocating(NullBlocks::never).isViewBlocking(NullBlocks::never));
    /** Thin black organic film left behind where NULLROOT grows. */
    public static final DeferredBlock<CarpetBlock> RESIDUE = BLOCKS.registerBlock("residue", CarpetBlock::new,
            BlockBehaviour.Properties.of().mapColor(MapColor.COLOR_BLACK).strength(0.1F).sound(SoundType.SLIME_BLOCK)
                    .noLootTable().pushReaction(PushReaction.DESTROY));

    // ---- Retro terrain (old-looking fragments and structures, Stages 2-4) ---------------
    public static final DeferredBlock<Block> RETRO_GRASS_BLOCK = BLOCKS.registerSimpleBlock("retro_grass_block",
            retro(MapColor.GRASS, 0.6F, SoundType.GRASS));
    public static final DeferredBlock<Block> RETRO_DIRT = BLOCKS.registerSimpleBlock("retro_dirt",
            retro(MapColor.DIRT, 0.5F, SoundType.GRAVEL));
    public static final DeferredBlock<Block> RETRO_STONE = BLOCKS.registerSimpleBlock("retro_stone",
            retro(MapColor.STONE, 1.5F, SoundType.STONE).requiresCorrectToolForDrops());
    public static final DeferredBlock<Block> RETRO_COBBLESTONE = BLOCKS.registerSimpleBlock("retro_cobblestone",
            retro(MapColor.STONE, 2.0F, SoundType.STONE).requiresCorrectToolForDrops());
    public static final DeferredBlock<Block> RETRO_MOSSY_COBBLESTONE = BLOCKS.registerSimpleBlock("retro_mossy_cobblestone",
            retro(MapColor.STONE, 2.0F, SoundType.STONE).requiresCorrectToolForDrops());
    public static final DeferredBlock<Block> RETRO_GRAVEL = BLOCKS.registerSimpleBlock("retro_gravel",
            retro(MapColor.STONE, 0.6F, SoundType.GRAVEL));
    public static final DeferredBlock<Block> RETRO_SAND = BLOCKS.registerSimpleBlock("retro_sand",
            retro(MapColor.SAND, 0.5F, SoundType.SAND));
    public static final DeferredBlock<RotatedPillarBlock> RETRO_LOG = BLOCKS.registerBlock("retro_log",
            RotatedPillarBlock::new, retro(MapColor.WOOD, 2.0F, SoundType.WOOD));
    public static final DeferredBlock<Block> RETRO_LEAVES = BLOCKS.registerSimpleBlock("retro_leaves",
            retro(MapColor.PLANT, 0.2F, SoundType.GRASS).noOcclusion().isSuffocating(NullBlocks::never).isViewBlocking(NullBlocks::never));
    public static final DeferredBlock<Block> RETRO_PLANKS = BLOCKS.registerSimpleBlock("retro_planks",
            retro(MapColor.WOOD, 2.0F, SoundType.WOOD));
    public static final DeferredBlock<Block> RETRO_BRICKS = BLOCKS.registerSimpleBlock("retro_bricks",
            retro(MapColor.COLOR_RED, 2.0F, SoundType.STONE).requiresCorrectToolForDrops());
    public static final DeferredBlock<TransparentBlock> RETRO_GLASS = BLOCKS.registerBlock("retro_glass", TransparentBlock::new,
            retro(MapColor.NONE, 0.3F, SoundType.GLASS).noOcclusion().isValidSpawn(NullBlocks::neverSpawn)
                    .isRedstoneConductor(NullBlocks::never).isSuffocating(NullBlocks::never).isViewBlocking(NullBlocks::never));

    // ---- The NULL dimension -------------------------------------------------------------
    public static final DeferredBlock<Block> VOID_PANEL = BLOCKS.registerSimpleBlock("void_panel", digital(MapColor.COLOR_BLACK, 0));
    public static final DeferredBlock<Block> GRID_PANEL = BLOCKS.registerSimpleBlock("grid_panel", digital(MapColor.COLOR_BLACK, 4));
    public static final DeferredBlock<Block> FRAME_BLOCK = BLOCKS.registerSimpleBlock("frame_block",
            digital(MapColor.SNOW, 12).emissiveRendering(NullBlocks::always));
    public static final DeferredBlock<Block> DATA_BLOCK = BLOCKS.registerSimpleBlock("data_block",
            digital(MapColor.COLOR_CYAN, 10).emissiveRendering(NullBlocks::always));
    public static final DeferredBlock<TransparentBlock> NULL_GLASS = BLOCKS.registerBlock("null_glass", TransparentBlock::new,
            digital(MapColor.NONE, 0).noOcclusion().isRedstoneConductor(NullBlocks::never)
                    .isSuffocating(NullBlocks::never).isViewBlocking(NullBlocks::never));
    public static final DeferredBlock<Block> GLOW_RED = glow("glow_red", MapColor.COLOR_RED);
    public static final DeferredBlock<Block> GLOW_GREEN = glow("glow_green", MapColor.COLOR_LIGHT_GREEN);
    public static final DeferredBlock<Block> GLOW_BLUE = glow("glow_blue", MapColor.COLOR_BLUE);
    public static final DeferredBlock<Block> GLOW_CYAN = glow("glow_cyan", MapColor.COLOR_CYAN);
    public static final DeferredBlock<Block> GLOW_MAGENTA = glow("glow_magenta", MapColor.COLOR_MAGENTA);
    public static final DeferredBlock<Block> GLOW_YELLOW = glow("glow_yellow", MapColor.COLOR_YELLOW);
    public static final DeferredBlock<Block> GLOW_WHITE = glow("glow_white", MapColor.SNOW);

    /** Every RGB glow block, in a fixed order (red, green, blue, cyan, magenta, yellow, white). */
    public static List<DeferredBlock<Block>> glowBlocks() {
        return List.of(GLOW_RED, GLOW_GREEN, GLOW_BLUE, GLOW_CYAN, GLOW_MAGENTA, GLOW_YELLOW, GLOW_WHITE);
    }

    /** The blocks used for "this block is wrong" corruption, most common first. */
    public static List<DeferredBlock<Block>> errorBlocks() {
        return List.of(BLACK_BLOCK, MISSING_BLOCK, ERROR_BLOCK, ERROR_STRIPES, ERROR_NOISE, ERROR_SHIFT, STATIC_BLOCK);
    }

    private NullBlocks() {
    }

    private static BlockBehaviour.Properties corrupted(MapColor color) {
        return BlockBehaviour.Properties.of()
                .mapColor(color)
                .strength(1.5F, 6.0F)
                .sound(NullSoundTypes.CORRUPTED)
                .noLootTable();
    }

    private static BlockBehaviour.Properties retro(MapColor color, float strength, SoundType sound) {
        return BlockBehaviour.Properties.of()
                .mapColor(color)
                .strength(strength, strength * 3.0F)
                .sound(sound);
    }

    /** Unbreakable building blocks of the NULL dimension. */
    private static BlockBehaviour.Properties digital(MapColor color, int light) {
        ToIntFunction<BlockState> emission = state -> light;
        return BlockBehaviour.Properties.of()
                .mapColor(color)
                .strength(-1.0F, 3600000.0F)
                .noLootTable()
                .isValidSpawn(NullBlocks::neverSpawn)
                .lightLevel(emission)
                .sound(SoundType.AMETHYST)
                .pushReaction(PushReaction.BLOCK);
    }

    private static DeferredBlock<Block> glow(String name, MapColor color) {
        return BLOCKS.registerSimpleBlock(name, digital(color, 15).emissiveRendering(NullBlocks::always));
    }

    private static boolean never(BlockState state, BlockGetter level, BlockPos pos) {
        return false;
    }

    private static boolean always(BlockState state, BlockGetter level, BlockPos pos) {
        return true;
    }

    private static Boolean neverSpawn(BlockState state, BlockGetter level, BlockPos pos, EntityType<?> type) {
        return false;
    }
}
